-- 1. Repair the authenticated A/B event batch recorder.
-- The historical function referenced a non-existent `ord` output column from
-- WITH ORDINALITY. Alias both generated columns explicitly and reject malformed
-- or stale post identifiers without aborting the whole batch.
CREATE OR REPLACE FUNCTION public.ml_record_feed_ab_events(p_events jsonb)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_user_id uuid := auth.uid();
  v_assignment record;
  v_count integer := 0;
BEGIN
  IF v_user_id IS NULL
     OR p_events IS NULL
     OR pg_catalog.jsonb_typeof(p_events) <> 'array' THEN
    RETURN 0;
  END IF;

  SELECT *
  INTO v_assignment
  FROM public.ml_recsys_v8_assignment(v_user_id, 'recsys_v8_main')
  LIMIT 1;

  WITH raw AS (
    SELECT events.e, events.ord
    FROM pg_catalog.jsonb_array_elements(p_events)
      WITH ORDINALITY AS events(e, ord)
    WHERE events.ord <= 100
  ),
  clean AS (
    SELECT
      CASE
        WHEN (raw.e->>'post_id') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
          THEN (raw.e->>'post_id')::uuid
        ELSE NULL::uuid
      END AS post_id,
      pg_catalog.left(COALESCE(NULLIF(raw.e->>'event_type', ''), 'view'), 40) AS event_type,
      pg_catalog.left(COALESCE(NULLIF(raw.e->>'surface', ''), 'feed'), 80) AS surface,
      CASE
        WHEN (raw.e->>'dwell_ms') ~ '^[0-9]+$'
          THEN LEAST(
            86400000::numeric,
            GREATEST(0::numeric, (raw.e->>'dwell_ms')::numeric)
          )::integer
        ELSE NULL::integer
      END AS dwell_ms,
      CASE
        WHEN (raw.e->>'weight') ~ '^-?[0-9]+(\.[0-9]+)?$'
          THEN GREATEST(-9.99::numeric, LEAST(9.99::numeric, (raw.e->>'weight')::numeric))
        ELSE 1::numeric
      END AS weight,
      CASE
        WHEN pg_catalog.jsonb_typeof(raw.e->'metadata') = 'object' THEN raw.e->'metadata'
        ELSE '{}'::jsonb
      END AS metadata
    FROM raw
    WHERE pg_catalog.jsonb_typeof(raw.e) = 'object'
  ),
  inserted AS (
    INSERT INTO public.ml_feed_experiment_events (
      user_id,
      experiment_key,
      variant,
      post_id,
      event_type,
      surface,
      dwell_ms,
      weight,
      metadata
    )
    SELECT
      v_user_id,
      COALESCE(v_assignment.experiment_key, 'recsys_v8_main'),
      COALESCE(v_assignment.variant, 'a'),
      clean.post_id,
      clean.event_type,
      clean.surface,
      clean.dwell_ms,
      clean.weight,
      clean.metadata
    FROM clean
    JOIN public.posts post ON post.id = clean.post_id
    WHERE clean.event_type IN (
      'view', 'impression', 'click', 'dwell_medium', 'dwell_long',
      'watch_complete', 'like', 'comment', 'share', 'save',
      'skip_fast', 'not_interested', 'hide', 'report'
    )
    RETURNING 1
  )
  SELECT pg_catalog.count(*)::integer INTO v_count FROM inserted;

  RETURN COALESCE(v_count, 0);
END;
$function$;

