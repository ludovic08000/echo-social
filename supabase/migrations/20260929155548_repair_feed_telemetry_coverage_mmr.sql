-- Extend creator features with the mean of available 256d item vectors. This
-- remains a privileged maintenance function; browser roles cannot execute it.
CREATE OR REPLACE FUNCTION public.ml_refresh_creator_features_v8(p_creator_id uuid)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_total_posts integer := 0;
  v_avg_watch numeric := 0;
  v_negative_rate numeric := 0;
  v_quality numeric := 0.5;
  v_novelty numeric := 0.5;
  v_embedding public.vector(256);
  v_embedding_count integer := 0;
BEGIN
  IF p_creator_id IS NULL THEN
    RETURN false;
  END IF;

  SELECT pg_catalog.count(*)::integer
  INTO v_total_posts
  FROM public.posts post
  WHERE post.user_id = p_creator_id
    AND (post.expires_at IS NULL OR post.expires_at > pg_catalog.now())
    AND post.created_at > pg_catalog.now() - '180 days'::pg_catalog.interval;

  SELECT
    COALESCE(pg_catalog.avg(features.avg_watch_time_ms), 0),
    COALESCE(
      pg_catalog.sum(features.negative_count)::numeric /
        GREATEST(1, pg_catalog.sum(features.positive_count + features.negative_count)),
      0
    )
  INTO v_avg_watch, v_negative_rate
  FROM public.posts post
  LEFT JOIN public.ml_post_features features ON features.post_id = post.id
  WHERE post.user_id = p_creator_id
    AND (post.expires_at IS NULL OR post.expires_at > pg_catalog.now())
    AND post.created_at > pg_catalog.now() - '90 days'::pg_catalog.interval;

  SELECT public.avg(item.embedding), pg_catalog.count(item.embedding)::integer
  INTO v_embedding, v_embedding_count
  FROM public.posts post
  JOIN public.ml_post_embeddings item ON item.post_id = post.id
  WHERE post.user_id = p_creator_id
    AND (post.expires_at IS NULL OR post.expires_at > pg_catalog.now())
    AND item.embedding IS NOT NULL;

  v_quality := LEAST(1.0, GREATEST(0.0,
    0.45
    + LEAST(0.30, COALESCE(v_avg_watch, 0) / 40000.0)
    - LEAST(0.35, COALESCE(v_negative_rate, 0) * 0.70)
  ));

  v_novelty := LEAST(1.0, GREATEST(0.0,
    CASE
      WHEN v_total_posts < 5 THEN 0.75
      WHEN v_total_posts < 20 THEN 0.62
      ELSE 0.48
    END
  ));

  INSERT INTO public.ml_creator_features (
    creator_id,
    embedding,
    embedding_post_count,
    embedding_updated_at,
    quality_score,
    novelty_score,
    fatigue_score,
    total_posts,
    avg_watch_time_ms,
    negative_feedback_rate,
    updated_at
  )
  VALUES (
    p_creator_id,
    v_embedding,
    COALESCE(v_embedding_count, 0),
    CASE WHEN v_embedding IS NULL THEN NULL ELSE pg_catalog.now() END,
    v_quality,
    v_novelty,
    LEAST(1.0, COALESCE(v_negative_rate, 0) * 1.2),
    COALESCE(v_total_posts, 0),
    COALESCE(v_avg_watch, 0),
    COALESCE(v_negative_rate, 0),
    pg_catalog.now()
  )
  ON CONFLICT (creator_id) DO UPDATE SET
    embedding = EXCLUDED.embedding,
    embedding_post_count = EXCLUDED.embedding_post_count,
    embedding_updated_at = EXCLUDED.embedding_updated_at,
    quality_score = EXCLUDED.quality_score,
    novelty_score = EXCLUDED.novelty_score,
    fatigue_score = EXCLUDED.fatigue_score,
    total_posts = EXCLUDED.total_posts,
    avg_watch_time_ms = EXCLUDED.avg_watch_time_ms,
    negative_feedback_rate = EXCLUDED.negative_feedback_rate,
    updated_at = pg_catalog.now();

  RETURN true;
END;
$function$;

REVOKE ALL ON FUNCTION public.ml_refresh_creator_features_v8(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.ml_refresh_creator_features_v8(uuid) TO service_role;

CREATE OR REPLACE FUNCTION public.ml_capture_feed_coverage_snapshot()
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_total_posts integer := 0;
  v_feature_rows integer := 0;
  v_semantic_embeddings integer := 0;
  v_tower_embeddings integer := 0;
  v_total_creators integer := 0;
  v_creator_rows integer := 0;
  v_creator_embeddings integer := 0;
  v_ab_24h integer := 0;
  v_ab_7d integer := 0;
  v_variant_a integer := 0;
  v_variant_b integer := 0;
  v_snapshot_id bigint;
  v_ready boolean := false;
BEGIN
  SELECT
    pg_catalog.count(*)::integer,
    pg_catalog.count(features.post_id)::integer,
    pg_catalog.count(features.embedding)::integer,
    pg_catalog.count(item.embedding)::integer,
    pg_catalog.count(DISTINCT post.user_id)::integer
  INTO
    v_total_posts,
    v_feature_rows,
    v_semantic_embeddings,
    v_tower_embeddings,
    v_total_creators
  FROM public.posts post
  LEFT JOIN public.ml_post_features features ON features.post_id = post.id
  LEFT JOIN public.ml_post_embeddings item ON item.post_id = post.id
  WHERE post.expires_at IS NULL OR post.expires_at > pg_catalog.now();

  SELECT
    pg_catalog.count(DISTINCT creator.creator_id)::integer,
    pg_catalog.count(DISTINCT creator.creator_id) FILTER (WHERE creator.embedding IS NOT NULL)::integer
  INTO v_creator_rows, v_creator_embeddings
  FROM public.ml_creator_features creator
  WHERE EXISTS (
    SELECT 1
    FROM public.posts post
    WHERE post.user_id = creator.creator_id
      AND (post.expires_at IS NULL OR post.expires_at > pg_catalog.now())
  );

  SELECT
    pg_catalog.count(*) FILTER (WHERE event.created_at > pg_catalog.now() - '24 hours'::pg_catalog.interval)::integer,
    pg_catalog.count(*)::integer,
    pg_catalog.count(*) FILTER (WHERE event.variant = 'a')::integer,
    pg_catalog.count(*) FILTER (WHERE event.variant = 'b')::integer
  INTO v_ab_24h, v_ab_7d, v_variant_a, v_variant_b
  FROM public.ml_feed_experiment_events event
  WHERE event.created_at > pg_catalog.now() - '7 days'::pg_catalog.interval;

  -- A multi-objective model remains gated until both data volume and coverage
  -- are meaningful, with balanced online telemetry in both active variants.
  v_ready :=
    v_total_posts >= 500
    AND v_total_creators >= 50
    AND v_semantic_embeddings >= pg_catalog.ceil(v_total_posts * 0.95)
    AND v_tower_embeddings >= pg_catalog.ceil(v_total_posts * 0.90)
    AND v_creator_embeddings >= pg_catalog.ceil(v_total_creators * 0.90)
    AND v_ab_7d >= 10000
    AND v_variant_a >= 4000
    AND v_variant_b >= 4000;

  INSERT INTO public.ml_feed_coverage_snapshots (
    total_active_posts,
    post_feature_rows,
    semantic_post_embeddings,
    tower_post_embeddings,
    total_active_creators,
    creator_feature_rows,
    creator_embeddings,
    ab_events_24h,
    ab_events_7d,
    variant_a_events_7d,
    variant_b_events_7d,
    post_feature_coverage_pct,
    semantic_embedding_coverage_pct,
    tower_embedding_coverage_pct,
    creator_feature_coverage_pct,
    creator_embedding_coverage_pct,
    multi_objective_ready,
    readiness_requirements
  )
  VALUES (
    v_total_posts,
    v_feature_rows,
    v_semantic_embeddings,
    v_tower_embeddings,
    v_total_creators,
    v_creator_rows,
    v_creator_embeddings,
    v_ab_24h,
    v_ab_7d,
    v_variant_a,
    v_variant_b,
    pg_catalog.round(100.0 * v_feature_rows / GREATEST(v_total_posts, 1), 2),
    pg_catalog.round(100.0 * v_semantic_embeddings / GREATEST(v_total_posts, 1), 2),
    pg_catalog.round(100.0 * v_tower_embeddings / GREATEST(v_total_posts, 1), 2),
    pg_catalog.round(100.0 * v_creator_rows / GREATEST(v_total_creators, 1), 2),
    pg_catalog.round(100.0 * v_creator_embeddings / GREATEST(v_total_creators, 1), 2),
    v_ready,
    pg_catalog.jsonb_build_object(
      'min_active_posts', 500,
      'min_active_creators', 50,
      'min_semantic_coverage_pct', 95,
      'min_tower_coverage_pct', 90,
      'min_creator_embedding_coverage_pct', 90,
      'min_ab_events_7d', 10000,
      'min_events_per_variant_7d', 4000
    )
  )
  RETURNING id INTO v_snapshot_id;

  RETURN v_snapshot_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.ml_capture_feed_coverage_snapshot() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.ml_capture_feed_coverage_snapshot() TO service_role;

-- Create feature shells for every active post so the trainer can fill missing
-- semantic embeddings instead of skipping pre-existing rows forever.
CREATE OR REPLACE FUNCTION public.ml_backfill_feed_feature_shells()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_shells integer := 0;
  v_creators integer := 0;
  v_creator record;
  v_snapshot_id bigint;
BEGIN
  INSERT INTO public.ml_post_features (
    post_id,
    topics,
    hashtags,
    sentiment,
    quality_score,
    language,
    has_media,
    engagement_velocity,
    ctr,
    view_count,
    positive_count,
    negative_count,
    extracted_at,
    updated_at,
    embedding_text,
    creator_id
  )
  SELECT
    post.id,
    '{}'::text[],
    '{}'::text[],
    0,
    0.5,
    'und',
    post.image_url IS NOT NULL,
    0,
    0,
    0,
    0,
    0,
    pg_catalog.now(),
    pg_catalog.now(),
    pg_catalog.left(pg_catalog.btrim(COALESCE(post.body, '')), 2000),
    post.user_id
  FROM public.posts post
  WHERE post.expires_at IS NULL OR post.expires_at > pg_catalog.now()
  ON CONFLICT (post_id) DO UPDATE SET
    creator_id = EXCLUDED.creator_id,
    embedding_text = CASE
      WHEN COALESCE(public.ml_post_features.embedding_text, '') = '' THEN EXCLUDED.embedding_text
      ELSE public.ml_post_features.embedding_text
    END,
    has_media = EXCLUDED.has_media;

  GET DIAGNOSTICS v_shells = ROW_COUNT;

  FOR v_creator IN
    SELECT DISTINCT post.user_id AS creator_id
    FROM public.posts post
    WHERE (post.expires_at IS NULL OR post.expires_at > pg_catalog.now())
      AND post.user_id IS NOT NULL
  LOOP
    PERFORM public.ml_refresh_creator_features_v8(v_creator.creator_id);
    v_creators := v_creators + 1;
  END LOOP;

  v_snapshot_id := public.ml_capture_feed_coverage_snapshot();

  RETURN pg_catalog.jsonb_build_object(
    'feature_rows_touched', v_shells,
    'creators_refreshed', v_creators,
    'coverage_snapshot_id', v_snapshot_id
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.ml_backfill_feed_feature_shells() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.ml_backfill_feed_feature_shells() TO service_role;

-- Secure Lovable Cloud cron wrapper. The credential stays in Vault and never
-- appears in cron.job or source code.
CREATE OR REPLACE FUNCTION public.ml_feed_train_cron_tick()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_project_url text := 'https://vkpmoqfzrihcijjochks.supabase.co';
  v_service_role text;
BEGIN
  SELECT secret.decrypted_secret
  INTO v_service_role
  FROM vault.decrypted_secrets secret
  WHERE secret.name = 'email_queue_service_role_key'
  LIMIT 1;

  IF v_service_role IS NULL OR pg_catalog.length(v_service_role) = 0 THEN
    RAISE NOTICE 'Vault service credential missing; skipping ml-feed-train';
    RETURN;
  END IF;

  PERFORM net.http_post(
    url := v_project_url || '/functions/v1/ml-feed-train',
    headers := pg_catalog.jsonb_build_object(
      'Authorization', 'Bearer ' || v_service_role,
      'Content-Type', 'application/json'
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 55000
  );
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'ml-feed-train HTTP call failed: %', SQLERRM;
END;
$function$;

REVOKE ALL ON FUNCTION public.ml_feed_train_cron_tick() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.ml_feed_train_cron_tick() TO service_role;

-- Remove only known obsolete/broken duplicate schedules, then install one
-- Vault-backed hourly job. Do not touch the working two-tower embeddings job.
DO $schedule_ml_feed_train$
DECLARE
  v_job record;
BEGIN
  IF pg_catalog.to_regclass('cron.job') IS NULL THEN
    RAISE NOTICE 'pg_cron is unavailable; ml-feed-train schedule was not installed';
    RETURN;
  END IF;

  FOR v_job IN EXECUTE
    'SELECT jobid FROM cron.job WHERE jobname = ANY($1)'
    USING ARRAY[
      'ml-feed-train-hourly',
      'ml-twotower-train-nightly',
      'ml-twotower-train-daily',
      'forsure-ml-feed-train-hourly'
    ]::text[]
  LOOP
    EXECUTE 'SELECT cron.unschedule($1)' USING v_job.jobid;
  END LOOP;

  EXECUTE 'SELECT cron.schedule($1, $2, $3)'
  USING
    'forsure-ml-feed-train-hourly',
    '17 * * * *',
    'SELECT public.ml_feed_train_cron_tick();';
END;
$schedule_ml_feed_train$;

-- Safe, idempotent initial fill. Semantic embeddings are generated by the Edge
-- trainer after deployment; this call only creates shells and baseline metrics.
SELECT public.ml_backfill_feed_feature_shells();
