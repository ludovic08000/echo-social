import { build } from 'esbuild';
import { mkdir,readFile,realpath,writeFile } from 'node:fs/promises';
import { resolve,sep } from 'node:path';
import { isBuiltin } from 'node:module';
import type { Plugin } from 'vite';

/** Bundle le runtime serveur avec le lockfile audité, pas un npm: résolu à nouveau dans le Cloud. */
export function secureMcpPlugin(): Plugin {
  return {
    name: 'forsure-locked-mcp-runtime',
    async configResolved(config) {
      const project = await readFile(resolve(config.root, 'supabase/config.toml'), 'utf8');
      const projectRef = project.match(/^project_id\s*=\s*"([a-z0-9]+)"/m)?.[1];
      if (!projectRef) throw new Error('MCP_PROJECT_REF_MISSING');
      const sdk = JSON.parse(await readFile(resolve(config.root, 'node_modules/@modelcontextprotocol/sdk/package.json'), 'utf8'));
      if (sdk.version !== '1.32.1') throw new Error('MCP_UNAUDITED_SDK_VERSION');
      const result = await build({
        absWorkingDir: config.root,
        stdin: {
          contents: `import mcp from './src/lib/mcp/index.ts';\nimport {createSupabaseHandler} from '@lovable.dev/mcp-js/stacks/supabase';\nexport default createSupabaseHandler(mcp,{functionName:'mcp'});`,
          resolveDir: config.root, sourcefile: 'forsure-mcp-handler.ts', loader: 'ts',
        },
        bundle: true, platform: 'node', target: 'es2022', format: 'esm', packages: 'bundle',
        plugins: [{ name: 'deno-no-worker-bindings', setup(bundler) {
          // Branche de télémétrie optionnelle du SDK, indisponible dans Deno comme dans Node.
          bundler.onResolve({ filter: /^cloudflare:workers$/ }, () => ({ path: 'unavailable', namespace: 'deno-platform' }));
          bundler.onLoad({ filter: /.*/, namespace: 'deno-platform' }, () => ({
            contents: 'throw new Error("CLOUDFLARE_BINDINGS_UNAVAILABLE_IN_DENO");export const env=undefined;', loader: 'js',
          }));
        } }],
        outfile: resolve(config.root, 'supabase/functions/_shared/generated/mcp-handler.mjs'),
        define: { 'import.meta.env.VITE_SUPABASE_PROJECT_ID': JSON.stringify(projectRef) },
        banner: { js: '// Generated by scripts/secure-mcp.ts. MCP SDK 1.32.1, locked by package-lock.json.\nimport {createRequire as __forsureCreateRequire} from "node:module";\nconst require=__forsureCreateRequire(import.meta.url);' },
        write:false,sourcemap: false, metafile: true, legalComments: 'eof',
      });
      const external = Object.values(result.metafile!.outputs).flatMap(output => output.imports)
        .filter(entry => entry.external && !isBuiltin(entry.path));
      if (external.length) throw new Error('MCP_UNBUNDLED_DEPENDENCY:'+external.map(entry=>entry.path).join(','));
      const sdkInputs=Object.keys(result.metafile!.inputs).filter(file=>file.replace(/\\/g,'/').includes('/@modelcontextprotocol/sdk/'));
      const sdkRoot=await realpath(resolve(config.root,'node_modules/@modelcontextprotocol/sdk'));
      const resolvedSdkInputs=await Promise.all(sdkInputs.map(file=>realpath(resolve(config.root,file))));
      if(!resolvedSdkInputs.length||resolvedSdkInputs.some(file=>file!==sdkRoot&&!file.startsWith(`${sdkRoot}${sep}`)))
        throw new Error('MCP_UNEXPECTED_NESTED_SDK');
      await mkdir(resolve(config.root,'supabase/functions/_shared/generated'),{recursive:true});
      for(const output of result.outputFiles!){
        let previous:string|null=null;
        try {previous=await readFile(output.path,'utf8')}catch{/* Première génération. */}
        if(previous!==output.text)await writeFile(output.path,output.contents);
      }
    },
  };
}
